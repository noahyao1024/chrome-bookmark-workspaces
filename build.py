"""Generate the shared browser/JXA code and validated runtime configuration."""
from pathlib import Path
import argparse
import json
import re
from urllib.parse import urlsplit, parse_qsl

ROOT = Path(__file__).resolve().parent


def read_config(path=None):
    value = json.loads(Path(path or ROOT/'config.example.json').read_text())
    if not isinstance(value, dict) or type(value.get('version')) is not int or value['version'] != 1:
        raise ValueError('Config version must be 1')
    if set(value) - {'version','profile','entries'}:
        raise ValueError('Unknown config field')
    profile = value.get('profile', 'Default')
    if not isinstance(profile, str) or not re.fullmatch(r'[A-Za-z0-9 _.-]+', profile) or profile in ('.', '..'):
        raise ValueError('Use a Chrome profile directory name, not a path')
    entries = value.get('entries', [])
    if not isinstance(entries, list):
        raise ValueError('entries must be an array')
    ids = set()
    for entry in entries:
        if not isinstance(entry, dict) or not isinstance(entry.get('id'), str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', entry['id']):
            raise ValueError('Each entry needs a unique id')
        if set(entry) - {'id','url','scope'} or not isinstance(entry.get('url'), str):
            raise ValueError('An entry accepts only id, url and scope')
        if entry['id'] in ids:
            raise ValueError('Duplicate entry id')
        ids.add(entry['id'])
        target = urlsplit(entry.get('url', ''))
        scope = entry.get('scope', {})
        if not isinstance(scope, dict) or set(scope) - {'origin','pathPrefix','queryKeys','allowFragment'}:
            raise ValueError('Invalid scope fields')
        origin = urlsplit(scope.get('origin', ''))
        prefix = scope.get('pathPrefix', '')
        if target.scheme not in ('http', 'https') or not target.netloc or target.username or target.password:
            raise ValueError('Entry URLs must be HTTP(S) without credentials')
        if scope.get('origin') != target.scheme+'://'+target.netloc or origin.path or origin.query or origin.fragment:
            raise ValueError('Scope origin must exactly match the entry URL origin')
        if not isinstance(prefix, str) or not prefix.startswith('/') or not prefix.endswith('/') or '%' in prefix:
            raise ValueError('pathPrefix must start and end with /')
        if '%' in target.path or not (target.path == prefix[:-1] or target.path.startswith(prefix)):
            raise ValueError('Entry URL must be inside its pathPrefix')
        keys = scope.get('queryKeys', [])
        if keys != '*' and (not isinstance(keys, list) or not all(isinstance(k, str) for k in keys)):
            raise ValueError('queryKeys must be an array or "*"')
        if 'allowFragment' in scope and not isinstance(scope['allowFragment'], bool):
            raise ValueError('allowFragment must be boolean')
        if target.fragment and scope.get('allowFragment') is not True:
            raise ValueError('This entry URL requires allowFragment')
        if keys != '*' and any(key not in keys for key, _ in parse_qsl(target.query, keep_blank_values=True)):
            raise ValueError('Entry URL query keys must be listed in queryKeys')
    return {'version': 1, 'profile': profile, 'entries': entries}


def build(output=ROOT, config=None):
    output = Path(output)
    value = config or read_config()
    extension = output/'bookmark-groups-extension'
    extension.mkdir(parents=True, exist_ok=True)
    core = (ROOT/'alias-core.js').read_text()
    script = output/'chrome-alias.js'
    script.write_text('#!/usr/bin/osascript -l JavaScript\n'+core+'\n'+(ROOT/'adapter.js').read_text())
    script.chmod(0o755)
    (extension/'alias-core.mjs').write_text('// Generated by build.py.\n'+core+'\nexport default BookmarkWorkspaces;\n')
    (extension/'entry-reuse-config.mjs').write_text('// Generated by build.py.\nexport default '+json.dumps(value, indent=2)+';\n')
    (output/'alias-config.json').write_text(json.dumps({'profile': value['profile']})+'\n')
    (output/'entry-reuse-config.json').write_text(json.dumps(value, indent=2)+'\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT)
    parser.add_argument('--config', type=Path)
    args = parser.parse_args()
    if args.config and args.config.resolve() != (ROOT/'config.example.json').resolve() and args.output.resolve() == ROOT:
        parser.error('Keep private config out of the source tree: use --output dist/custom')
    try:
        build(args.output, read_config(args.config))
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
